// Placeholders used when exporting without real keys (the committed copy).
const (
	placeholderAlertKey = "YOUR_ORCHESTRATION_ROUTING_KEY"
	placeholderChange   = "YOUR_%s_CHANGE_KEY" // %s = service name, upper-cased
)

// cmdExport writes every scenario step as plain, ready-to-send JSON, plus
// send.sh / resolve.sh, so the events can be used from curl, Postman or any
// other tool without this app.
func cmdExport(args []string) error {
	var c common
	fs := flag.NewFlagSet("export", flag.ExitOnError)
	c.register(fs, true)
	dir := fs.String("dir", "", "output folder (default: payloads/rendered in a checkout, else ~/Desktop/Reinvent payloads)")
	withKeys := fs.Bool("keys", false, "fill in this account's real routing keys instead of placeholders")
	open := fs.Bool("open", false, "open the folder in Finder afterwards")
	fs.Parse(args)
	if err := c.resolveRoot(); err != nil {
		return err
	}
	sc, err := loadScenario(c.scenarioPath())
	if err != nil {
		return err
	}
	out := *dir
	if out == "" {
		if isCheckout(c.root) && !*withKeys {
			out = filepath.Join(c.root, "payloads", "rendered")
		} else {
			home, _ := os.UserHomeDir()
			out = filepath.Join(home, "Desktop", "Reinvent payloads")
		}
	}

	alertKey, changeKeys := placeholderAlertKey, map[string]string{}
	if *withKeys {
		if alertKey, err = c.key(); err != nil {
			return err
		}
		if changeKeys, err = c.changeKeys(); err != nil {
			return err
		}
	}
	changeKeyFor := func(svc string) string {
		if k, ok := changeKeys[svc]; ok {
			return k
		}
		if k, ok := changeKeys["*"]; ok {
			return k
		}
		return fmt.Sprintf(placeholderChange, strings.ToUpper(strings.ReplaceAll(svc, "-", "_")))
	}

	files, err := renderExport(sc, alertKey, changeKeyFor)
	if err != nil {
		return err
	}
	if err := os.RemoveAll(out); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(out, "resolve"), 0o755); err != nil {
		return err
	}
	for name, data := range files {
		mode := os.FileMode(0o644)
		if strings.HasSuffix(name, ".sh") {
			mode = 0o755
		}
		if *withKeys && !strings.HasSuffix(name, ".sh") && !strings.HasSuffix(name, ".md") {
			mode = 0o600 // contains real routing keys
		}
		if err := os.WriteFile(filepath.Join(out, name), data, mode); err != nil {
			return err
		}
	}
	fmt.Printf("Exported %d events to %s\n", len(sc.Steps), out)
	if *withKeys {
		fmt.Println("These files contain your real routing keys. Don't share or commit them.")
	}
	if *open {
		_ = exec.Command("open", out).Run()
	}
	return nil
}

func isCheckout(root string) bool {
	_, err := os.Stat(filepath.Join(root, "app", "main.go"))
	return err == nil
}

var slugRe = regexp.MustCompile(`[^a-z0-9]+`)

func slug(s string) string {
	return strings.Trim(slugRe.ReplaceAllString(strings.ToLower(s), "-"), "-")
}

// renderExport renders the scenario into file name → content. Alert
// timestamps are dropped (PagerDuty uses the time it receives the event);
// change-event timestamps keep their offset relative to export time.
func renderExport(sc *Scenario, alertKey string, changeKeyFor func(string) string) (map[string][]byte, error) {
	files := map[string][]byte{}
	var send, resolve strings.Builder
	header := `#!/bin/sh
# Generated by Reinvent (./trigger export). Posts the events in order with curl.
# EU accounts: PD_EVENTS_URL=https://events.eu.pagerduty.com ./%s
set -eu
cd "$(dirname "$0")"
URL=${PD_EVENTS_URL:-https://events.pagerduty.com}
post() { printf '%%-50s ' "$2"; curl -sS -X POST "$URL$1" -H 'Content-Type: application/json' -d @"$2"; echo; }
`
	fmt.Fprintf(&send, header, "send.sh")
	fmt.Fprintf(&resolve, header, "resolve.sh")
	var readme strings.Builder
	fmt.Fprintf(&readme, "# %s: ready-to-send events\n\nGenerated from `payloads/scenario.json` by `./trigger export`. Plain JSON for the PagerDuty Events API v2: send them with `./send.sh`, Postman or any HTTP client, then close the alerts with `./resolve.sh`.\n\n", sc.Name)
	readme.WriteString("| # | File | Endpoint | Routed to |\n|---|---|---|---|\n")

	for i, st := range sc.Steps {
		body, err := sc.render(st)
		if err != nil {
			return nil, err
		}
		svc := routedTo(body)
		name := fmt.Sprintf("%02d-%s.json", i+1, slug(st.Name))
		path := "/v2/enqueue"
		if st.Type == "change" {
			path = "/v2/change/enqueue"
			body["routing_key"] = changeKeyFor(svc)
		} else {
			body["routing_key"] = alertKey
			if p, ok := body["payload"].(map[string]any); ok {
				delete(p, "timestamp")
			}
		}
		data, err := marshalPretty(body)
		if err != nil {
			return nil, err
		}
		files[name] = data
		fmt.Fprintf(&send, "post %s %s\n", path, name)
		if wait, _ := time.ParseDuration(st.WaitAfter); wait > 0 && i < len(sc.Steps)-1 {
			fmt.Fprintf(&send, "sleep %d\n", int(wait.Seconds()))
		}
		via := fmt.Sprintf("`%s` (Reinvent Patient orchestration, dynamic routing)", svc)
		if st.Type == "change" {
			via = fmt.Sprintf("`%s` (its change integration key)", svc)
		}
		fmt.Fprintf(&readme, "| %d | `%s` | `%s` | %s |\n", i+1, name, path, via)

		if st.Type == "alert" {
			body["event_action"] = "resolve"
			rdata, err := marshalPretty(body)
			if err != nil {
				return nil, err
			}
			rname := filepath.Join("resolve", name)
			files[rname] = rdata
			fmt.Fprintf(&resolve, "post /v2/enqueue %s\n", rname)
		}
	}
	readme.WriteString(`
## Notes

- **Routing keys.** Alerts use the global orchestration key, and change events use each service's own change key. In the committed copy these are placeholders (` + "`" + placeholderAlertKey + "`" + `, ` + "`YOUR_<SERVICE>_CHANGE_KEY`" + `). Export with ` + "`./trigger export -keys`" + ` (menu: Export payloads) to get a copy with your real keys.
- **Timestamps.** Alerts have none, so PagerDuty uses the time it receives them. Change events keep a timestamp backdated from the export time; re-export for a fresh one.
- **Resolve** files are the full alert with ` + "`event_action: resolve`" + `, so dynamic routing takes them to the same service.
- Every alert carries ` + "`custom_details.service`" + `, which the orchestration routes on and uses to add ` + "`custom_details.runbook.github`" + `.
`)
	files["send.sh"] = []byte(send.String())
	files["resolve.sh"] = []byte(resolve.String())
	files["README.md"] = []byte(readme.String())
	return files, nil
}

func marshalPretty(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
